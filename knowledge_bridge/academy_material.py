DOCS_REPO = "https://github.com/academiadoprogramador-fullstack/docs"
DOCS_HOST = "academiadoprogramador-fullstack.github.io"
SHA_RE = re.compile(r"^[a-f0-9]{40}$")
MAX_DOCS = 250
MAX_TERMS = 240
ALLOW_MATERIAL_IN_AI_PROMPT = False  # User approval required before enabling.


def official_route(url: str) -> str | None:
    """No redirect or arbitrary host; normalize Docusaurus /docs base."""
    if not isinstance(url, str) or len(url) > 1700:
        return None
    try:
        p = urlsplit(url)
        if (p.scheme != "https" or p.hostname != DOCS_HOST or p.port is not None
                or p.username or p.password or not p.path.startswith("/docs/")):
            return None
        raw = unquote(p.path[len("/docs/"):], encoding="utf-8", errors="strict")
        parts = raw.strip("/").split("/")
        if ("\\" in raw or "\x00" in raw
                or any(x in ("", ".", "..") for x in parts)):
            return None
        return "/" + "/".join(parts)
    except (ValueError, UnicodeError):
        return None


def _slug_part(value: str) -> str:
    text = unicodedata.normalize("NFKD",value).encode("ascii","ignore").decode().casefold()
    text = re.sub(r"^\d{1,3}\s*[-_.]\s*","",text)
    return re.sub(r"-+","-",re.sub(r"[^a-z0-9]+","-",text)).strip("-")


def route_for_path(path: str) -> str:
    """Docusaurus autogenerated route when a markdown page lacks slug."""
    parts = list(PurePosixPath(path).parts)
    if len(parts)<2 or parts[0]!="docs" or not path.endswith(".md"):
        return ""
    parts[-1]=parts[-1][:-3]
    route=[_slug_part(x) for x in parts[1:]]
    if route and route[-1]=="index":
        route.pop()
    return "/" + "/".join(route) if route and all(route) else ""


def _frontmatter(text: str):
    if not text.startswith("---\n"):
        return "",[],"",0
    lines=text.splitlines()
    try:
        end=lines.index("---",1)
    except ValueError:
        return "",[],"",0
    if end>180:
        return "",[],"",0
    slug,title,tags="","",[]
    collecting=False
    for line in lines[1:end]:
        m=re.match(r"^([a-zA-Z][\w-]*):\s*(.*?)\s*$",line)
        if m:
            key,val=m.group(1).casefold(),m.group(2).strip().strip("'\"")
            collecting=key=="tags"
            if key=="slug":slug=val[:220]
            elif key=="title":title=val[:180]
            elif key=="tags" and val.startswith("[") and val.endswith("]"):
                tags.extend(t.strip(" '\"")[:90] for t in val[1:-1].split(","))
                collecting=False
            continue
        if collecting:
            m=re.match(r"^\s*-\s+([\w-]{2,90})\s*$",line)
            if m:tags.append(m.group(1))
    return slug,list(dict.fromkeys(tags))[:80],title,end


def _route_from_slug(slug: str) -> str:
    slug=unquote(slug.strip())
    parts=slug.strip("/").split("/")
    if (not slug or "\\" in slug or "?" in slug or "#" in slug
            or any(x in ("", ".", "..") for x in parts)):
        return ""
    return "/" + "/".join(parts)


def _key(value: str) -> str:
    return " ".join(re.findall(r"[a-z0-9]+",_ascii(value.replace("-"," "))))


def extract_material(raw: str, path: str) -> dict:
    """Only title, tags, heading, inline code and bold spans are evidence."""
    raw=raw[:300_000]
    slug,tags,front_title,front_end=_frontmatter(raw)
    route=_route_from_slug(slug) if slug else route_for_path(path)
    lines=raw.splitlines()[:7000]
    headings=[re.sub(r"[#*]+","",m.group(1)).strip()[:180]
              for line in lines[front_end+1:]
              if (m:=re.match(r"^#{1,6}\s+(.+)",line))]
    title=front_title or (headings[0] if headings else PurePosixPath(path).stem[:180])
    terms,seen=[],set()

    def add(name, line, origin):
        name=re.sub(r"\s+"," ",str(name)).strip(" #*")
        if not 3<=len(name)<=90 or len(terms)>=MAX_TERMS:
            return
        key=(_key(name),origin)
        if not key[0] or key in seen:
            return
        seen.add(key)
        # Original one-based line and three original lines; evidence is data.
        excerpt=[x[:210] for x in lines[max(0,line-2):max(0,line-2)+3]]
        while len(excerpt)<3:excerpt.append("")
        terms.append({"name":name,"line":line,"snippet":"\n".join(excerpt),"origin":origin})

    fenced=False
    for index,line in enumerate(lines,1):
        if line.lstrip().startswith(("~~~","\x60\x60\x60")):
            fenced=not fenced
            continue
        if fenced or index<=front_end+1:
            continue
        if (m:=re.match(r"^#{1,6}\s+(.+)",line)):
            add(m.group(1),index,"titulo")
        for m in re.finditer(r"(?<!\*)\*\*([^*\r\n]{3,90})\*\*(?!\*)",line):
            add(m.group(1),index,"negrito")
        for m in re.finditer(r"(?<!\x60)\x60([^\x60\r\n]{3,90})\x60(?!\x60)",line):
            add(m.group(1),index,"codigo")
    concepts=[]
    for tag in tags:
        if not tag.startswith("conceito-"):
            continue
        term=tag[len("conceito-"):].replace("-"," ")
        if not term or len(term)>80:
            continue
        matching=next((x for x in terms if _key(x["name"])==_key(term)),None)
        written=matching["name"] if matching else term
        lineno=matching["line"] if matching else next(
            (i for i,line in enumerate(lines,1) if tag in line),1)
        concepts.append({"tag":tag,"name":written,"line":lineno})
        add(written,lineno,"tag")
    return {"route":route,"title":title,"tags":tags,
            "terms":terms[:MAX_TERMS],"concepts":concepts[:80]}


def _compressed_alias(question: str, term: str) -> bool:
    """Distinctive one-word ASR contraction of two or three technical words."""
    heard=tokens(focus_question(question))
    expected=tokens(term,identifier=True)
    if len(heard)!=1 or not 2<=len(expected)<=3:
        return False
    word=heard[0][1]
    whole="".join(x[1] for x in expected)
    if (len(heard[0][0])<6 or len(whole)<8 or len(expected[0][1])<4
            or is_generic_code_term(term) or word[:2]!=whole[:2]):
        return False
    a,b=_consonants(word),_consonants(whole)
    return (len(a)>=3 and len(b)>=4
            and SequenceMatcher(None,a,b,autojunk=False).ratio()>=0.78
            and SequenceMatcher(None,word,whole,autojunk=False).ratio()>=0.51)


def match_material_question(question: str, materials: list[dict]) -> dict | None:
    """Only use the question and the same lesson's pinned official document."""
    if not isinstance(question,str) or not question.strip():
        return None
    focus=focus_question(question)
    if re.search(r"\b\w+(?:ção|ções|dade|dades)\b",focus.casefold()):
        return None
    spoken=tokens(focus)
    if not spoken or (len(spoken)>8 and not re.search(r'["“”\x27]',question)):
        return None
    matches=[]
    for material in materials[:30]:
        sha,path=material.get("commit_sha",""),material.get("path","")
        if not SHA_RE.fullmatch(str(sha)) or not str(path).startswith("docs/") or ".." in str(path).split("/"):
            continue
        for t in material.get("terms",[])[:MAX_TERMS]:
            name=t.get("name","") if isinstance(t,dict) else ""
            if not isinstance(name,str) or len(name)>90 or is_generic_code_term(name):
                continue
            score=_ratio(spoken,tokens(name,identifier=True))
            if score is None and _compressed_alias(question,name):
                score=(0.85,1,0.80)
            if score is not None:
                matches.append((score,material,t))
    if not matches:
        return None
    matches.sort(key=lambda x:(-x[0][0],-x[0][1],-x[0][2],
                               x[1]["path"],x[2]["line"]))
    score,m,t=matches[0]
    return {"kind":"material_oficial_congelado","candidate":t["name"],
            "repo":DOCS_REPO,"sha":m["commit_sha"],"path":m["path"],
            "line":t["line"],"snippet":t["snippet"],"title":m["title"],
            "lesson":m["lesson"],"similarity":round(score[2],3)}




_CONTEXT_NAME = re.compile(r"^(Aula-\d{3,4})(?:-auto-[A-Za-z0-9]+)?\.json$")
_CONTEXT_URL = re.compile(r"https://[^\s<>'\"\\]+", re.I)


def saved_official_context_urls(store) -> list[tuple[str, str]]:
    """Find legacy official URLs in saved Classroom JSON, without modifying it.

    Only the context's explicit lesson, verified against the filename, may be
    used. The original JSON is never rewritten or interpreted as instructions.
    """
    folder = store.vault / "99-Anexos" / "Contexto-Classroom"
    if not folder.is_dir() or folder.is_symlink():
        return []
    found = set()
    for path in sorted(folder.glob("*.json")):
        match = _CONTEXT_NAME.fullmatch(path.name)
        if not match or path.is_symlink():
            continue
        try:
            if path.stat().st_size > 256_000:
                continue
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, ValueError):
            continue
        lesson = match.group(1)
        if not isinstance(payload, dict) or payload.get("aula") != lesson:
            continue
        values = []
        for field in ("links", "descricao", "atividades", "videos"):
            value = payload.get(field)
            if isinstance(value, str):
                values.append(value[:22_000])
            elif isinstance(value, list):
                for item in value[:50]:
                    if isinstance(item, str):
                        values.append(item[:1_800])
                    elif isinstance(item, dict) and isinstance(item.get("url"), str):
                        values.append(item["url"][:1_800])
        for value in values:
            for candidate in _CONTEXT_URL.findall(value):
                url = candidate.rstrip(").,;]}")
                if official_route(url) is not None:
                    found.add((lesson, url))
    return sorted(found)


def recover_saved_official_material(store, *, skip_urls=()) -> dict:
    """Idempotent rebuild-time recovery, with deferred retry on GitHub errors."""
    candidates = saved_official_context_urls(store)
    if not candidates:
        return {"linked": 0, "paused": False, "pending": 0}
    existing = {}
    pending = []
    for lesson, url in candidates:
        if lesson not in existing:
            existing[lesson] = {row["url"] for row in store.academy_docs_for_lesson(lesson)}
        if url not in existing[lesson] and (lesson, url) not in skip_urls:
            pending.append((lesson, url))
    if not pending:
        return {"linked": 0, "paused": False, "pending": 0}
    resolver = AcademyDocs(store)
    linked = 0
    for index, (lesson, url) in enumerate(pending):
        try:
            created, _ = resolver.attach(lesson, url)
        except (OSError, ValueError, RuntimeError):
            # A rate limit, permission issue or GitHub outage must not block
            # rebuilding other notes. Leave the URLs intact for the next run.
            return {"linked": linked, "paused": True, "pending": len(pending) - index}
        if created:
            linked += 1
    return {"linked": linked, "paused": False, "pending": 0}


class AcademyDocs:
    """Resolve URLs via slugs and freeze the public docs main SHA once/lesson."""
    def __init__(self, store, reader=None, cache=None):
        self.store=store
        self.cache=cache if cache is not None else GithubCache(vault=store.vault)
        self.reader=reader if reader is not None else GithubCodeReader(cache=self.cache)
        self._indexes={}

    def _index(self,sha):
        if sha in self._indexes:
            return self._indexes[sha]
        key=("academy-docs-routes-v1",sha)
        saved=self.cache.get(key,private=False)
        if saved:
            try:
                decompressor=zlib.decompressobj()
                raw=decompressor.decompress(saved,300_001)
                if len(raw)<=300_000 and decompressor.eof:
                    record=json.loads(raw)
                    if record.get("sha")==sha and isinstance(record.get("routes"),dict):
                        self._indexes[sha]=record["routes"]
                        return record["routes"]
            except (ValueError,TypeError,UnicodeError,zlib.error):
                pass
        listing=self.reader.list_files(DOCS_REPO,sha,"docs")
        paths=sorted(x["path"] for x in listing["files"] if x["path"].endswith(".md"))
        if listing["truncated"] or len(paths)>MAX_DOCS:
            raise MappingError("Árvore dos docs incompleta; não é seguro resolver o material.")
        routes={}
        for path in paths:
            obj=self.reader.read_file(DOCS_REPO,sha,path)
            meta=extract_material(obj["content"],path)
            route=meta["route"]
            if route:
                if route in routes and routes[route]!=path:routes[route]=None
                else:routes[route]=path
        encoded=zlib.compress(json.dumps(
            {"sha":sha,"routes":routes},ensure_ascii=False).encode("utf-8"))
        self.cache.put(key,encoded,private=False)
        self._indexes[sha]=routes
        return routes

    def _head(self):
        result=self.reader.client._get(DOCS_REPO,"branches/main")
        sha=(result.get("commit") or {}).get("sha") if isinstance(result,dict) else None
        if not isinstance(sha,str) or not SHA_RE.fullmatch(sha.lower()):
            raise MappingError("Não foi possível confirmar o SHA main dos docs.")
        return sha.lower()


    def suggest_unassigned_lesson(self, url: str) -> tuple[str, str] | None:
        """Read-only hint from an analyzed TXT; NEVER attach without confirmation."""
        route = official_route(url)
        if route is None:
            return None
        sha = self._head()
        self.reader._privacy[DOCS_REPO] = False
        path = self._index(sha).get(route)
        if not path:
            return None
        doc = extract_material(self.reader.read_file(DOCS_REPO, sha, path)["content"], path)
        if doc["route"] != route:
            return None
        ignored = {"sobre", "aula", "conteudo", "introducao", "exemplo", "curso",
                   "com", "uma", "para", "dos", "das", "pelo", "pela", "como",
                   "este", "esta", "seus", "suas", "que", "de", "do", "da", "em"}
        def keywords(value):
            return {w for w in _key(value).split() if len(w) >= 4 and w not in ignored}
        title_words = keywords(doc["title"])
        tag_words = set()
        for tag in doc["tags"]:
            if tag.startswith(("conceito-", "tech-", "projeto-")):
                tag_words.update(keywords(tag.split("-", 1)[1]))
        term_words = set()
        for item in doc["terms"][:MAX_TERMS]:
            if isinstance(item, dict) and isinstance(item.get("name"), str):
                term_words.update(keywords(item["name"]))
        if not title_words:
            return None
        by_lesson = {}
        for src in self.store.sources("transcript"):
            lesson = src["lesson"]
            if not re.fullmatch(r"Aula-\d{3,4}", lesson or ""):
                continue
            if not isinstance(self.store.analysis(src["id"], src["digest"]), dict):
                continue
            target = self.store.vault / (src["stored_path"] or "")
            try:
                if (target.is_symlink() or not target.resolve().is_relative_to(self.store.vault)
                        or not target.is_file() or target.stat().st_size > 600_000):
                    continue
                content = target.read_text(encoding="utf-8-sig", errors="replace")
            except (OSError, ValueError):
                continue
            by_lesson.setdefault(lesson, set()).update(keywords(content))
        ranked = []
        for lesson, words in by_lesson.items():
            title_hits = title_words & words
            tag_hits = tag_words & words
            term_hits = term_words & words
            if (len(title_hits | tag_hits | term_hits) < 2 or
                    not (len(title_hits) >= 2 or
                         len(title_hits) >= 1 and len(tag_hits) >= 1)):
                continue
            score = 3 * len(title_hits) + 2 * len(tag_hits) + min(3, len(term_hits))
            if score >= 6:
                ranked.append((score, lesson, title_hits, tag_hits))
        ranked.sort(key=lambda item: (-item[0], item[1]))
        if not ranked or (len(ranked) > 1 and ranked[0][0] - ranked[1][0] < 3):
            return None
        _, lesson, title_hits, tag_hits = ranked[0]
        reason = "termos do título: " + ", ".join(sorted(title_hits)[:4])
        if tag_hits:
            reason += "; tags: " + ", ".join(sorted(tag_hits)[:3])
        return lesson, reason

    def attach(self,lesson: str,url: str) -> tuple[bool,str]:
        route=official_route(url)
        if route is None:
            return False,"Link fora do domínio oficial da Academia."
        if not re.fullmatch(r"Aula-\d{3,4}",lesson or ""):
            return False,"Link oficial sem aula identificada."
        sha=self.store.academy_docs_sha(lesson)
        if sha is None:
            sha=self.store.freeze_academy_docs(lesson,self._head())
        # Fixed known-public repository; no private bytes cached as plaintext.
        self.reader._privacy[DOCS_REPO]=False
        path=self._index(sha).get(route)
        if not path:
            return False,"Página dos docs sem arquivo .md no SHA congelado; link preservado."
        if any(row["url"]==url for row in self.store.academy_docs_for_lesson(lesson)):
            return False,"Material já cadastrado; SHA preservado."
        if len(self.store.academy_docs_for_lesson(lesson))>=30:
            return False,"Limite de 30 documentos oficiais por aula."
        doc=self.reader.read_file(DOCS_REPO,sha,path)
        parsed=extract_material(doc["content"],path)
        if parsed["route"]!=route:
            return False,"Documento não corresponde à rota do SHA congelado."
        saved=self.store.register_academy_doc(
            lesson,url,sha,path,parsed["title"],parsed["tags"],
            parsed["terms"],parsed["concepts"])
        return saved,("Material oficial ligado ao SHA "+sha[:12] if saved
                      else "Material já vinculado.")
